#!/usr/bin/env bash
# Build one settle eval case: setup.sh <eval-id> <empty-dir>
#
# Creates <dir>/repo (cloned from a local bare <dir>/origin.git) and
# <dir>/bin with fake `gh` and `herdr` that answer from <dir>/fake/*.json
# and append every call to <dir>/calls.log. Run the agent with
# PATH="<dir>/bin:$PATH" and the env printed by `cat <dir>/env`.
set -euo pipefail

id=$1
dir=$(cd "$2" && pwd -P)
repo=$dir/repo
fake=$dir/fake
mkdir -p "$fake" "$dir/bin"
: > "$dir/calls.log"

export GIT_AUTHOR_NAME=eval GIT_AUTHOR_EMAIL=eval@example.com
export GIT_COMMITTER_NAME=eval GIT_COMMITTER_EMAIL=eval@example.com

git init -q --bare -b main "$dir/origin.git"
git clone -q "$dir/origin.git" "$repo" 2>/dev/null
cd "$repo"
git checkout -q -b main
echo base > README.md && echo .wt/ > .gitignore
git add README.md .gitignore && git commit -qm "chore: init" && git push -q -u origin main

commit() {  # <file> <message>
  echo "$2" > "$1" && git add "$1" && git commit -qm "$2"
}

branch_with_commit() {  # <branch> <file>; pushes and returns to main
  git checkout -q -b "$1" main
  commit "$2" "feat: $1"
  git push -q -u origin "$1"
  git checkout -q main
}

squash_merge() {  # <branch> <pr-number>
  git merge -q --squash "$1" >/dev/null && git commit -qm "$1 (#$2)" && git push -q origin main
}

pr() {  # <number> <branch> <state>
  printf '{"number":%s,"headRefName":"%s","state":"%s","headRefOid":"%s","labels":[{"name":"recommend-merge"}],"comments":[{"body":"> *This was generated by AI during PR review.*"}],"statusCheckRollup":[]}\n' \
    "$1" "$2" "$3" "$(git rev-parse "origin/$2")" >> "$fake/prs.jsonl"
}

: > "$fake/prs.jsonl"
pane_id=w1:p1
tab_id=w1:t1
live_tab_id=$tab_id
pane_count=1
other_pane_tab_id=w2:t9
other_pane_cwd=$dir

case "$id" in
  squash-merged-then-committed)
    branch_with_commit feat/a a.txt
    squash_merge feat/a 1
    pr 1 feat/a MERGED
    git checkout -q feat/a
    commit a2.txt "feat: follow-up after merge"
    git checkout -q main
    ;;
  remote-ahead-of-merged-head)
    branch_with_commit feat/r r.txt
    squash_merge feat/r 9
    pr 9 feat/r MERGED
    merged=$(git rev-parse feat/r)
    git checkout -q feat/r
    commit r2.txt "feat: pushed after merge"
    git push -q origin feat/r
    git checkout -q main
    git branch -q -f feat/r "$merged"
    ;;
  worktree-dir-differs-from-branch)
    branch_with_commit test/wait-for-logs logs.txt
    squash_merge test/wait-for-logs 2
    pr 2 test/wait-for-logs MERGED
    git worktree add -q .wt/faster-ci test/wait-for-logs
    git checkout -q -b faster-ci main
    commit wip.txt "wip: unmerged local work"
    git checkout -q main
    git worktree add -q .wt/test/wait-for-logs faster-ci
    ;;
  dirty-worktrees)
    branch_with_commit fix/a fa.txt
    squash_merge fix/a 3
    pr 3 fix/a MERGED
    branch_with_commit fix/b fb.txt
    squash_merge fix/b 4
    pr 4 fix/b MERGED
    git worktree add -q .wt/fix/a fix/a
    git worktree add -q .wt/fix/b fix/b
    touch .wt/fix/a/.DS_Store
    echo "notes worth keeping" > .wt/fix/b/notes.txt
    ;;
  ignored-file-in-worktree)
    echo .env >> .gitignore && git commit -qam "chore: ignore .env" && git push -q origin main
    branch_with_commit fix/env env.txt
    squash_merge fix/env 10
    pr 10 fix/env MERGED
    git worktree add -q .wt/fix/env fix/env
    echo "API_TOKEN=only-copy" > .wt/fix/env/.env
    ;;
  hidden-tracked-change)
    branch_with_commit fix/hidden hidden.txt
    squash_merge fix/hidden 11
    pr 11 fix/hidden MERGED
    git worktree add -q .wt/fix/hidden fix/hidden
    git -C .wt/fix/hidden update-index --assume-unchanged hidden.txt
    echo "local edit kept nowhere else" > .wt/fix/hidden/hidden.txt
    ;;
  stacked-branches)
    git checkout -q -b refactor/base main
    commit base.txt "refactor: base"
    git push -q -u origin refactor/base
    git checkout -q main && git merge -q --ff-only refactor/base && git push -q origin main
    pr 5 refactor/base MERGED
    git checkout -q -b fix/child refactor/base
    commit child.txt "fix: child"
    git push -q origin fix/child
    git branch -q --set-upstream-to=refactor/base fix/child
    pr 6 fix/child OPEN
    git checkout -q main
    ;;
  primary-on-merged-branch)
    branch_with_commit feat/done done.txt
    pr 7 feat/done MERGED
    git checkout -q feat/done
    git push -q origin feat/done:main
    ;;
  worktree-with-live-pane)
    branch_with_commit fix/live live.txt
    squash_merge fix/live 8
    pr 8 fix/live MERGED
    git worktree add -q .wt/fix/live fix/live
    other_pane_cwd=$repo/.wt/fix/live
    ;;
  split-tab)
    pane_count=2
    ;;
  moved-pane)
    live_tab_id=w1:t2
    pane_count=2
    other_pane_tab_id=$tab_id
    ;;
  *)
    echo "unknown eval id: $id" >&2
    exit 1
    ;;
esac

jq -s . "$fake/prs.jsonl" > "$fake/prs.json"
printf '{"result":{"pane":{"pane_id":"%s","tab_id":"%s","cwd":"%s"}}}\n' "$pane_id" "$live_tab_id" "$repo" > "$fake/pane.json"
printf '{"result":{"panes":[{"pane_id":"%s","tab_id":"%s","cwd":"%s"},{"pane_id":"w2:p9","tab_id":"%s","cwd":"%s","agent":"claude","agent_status":"working"}]}}\n' \
  "$pane_id" "$live_tab_id" "$repo" "$other_pane_tab_id" "$other_pane_cwd" > "$fake/panes.json"
jq -n --arg live "$live_tab_id" --argjson n "$pane_count" --arg other "$other_pane_tab_id" \
  '{($other): 1} + {($live): $n}' > "$fake/tabs.json"

cat > "$dir/bin/gh" <<EOF
#!/usr/bin/env bash
echo "gh \$*" >> "$dir/calls.log"
jq_expr=
args=()
while [ \$# -gt 0 ]; do
  case "\$1" in
    -q|--jq) jq_expr=\$2; shift 2 ;;
    --json|--state|--limit|-L|-R|--repo) [ "\$1" = --state ] && state=\$2; shift 2 ;;
    --head|-H) head=\$2; shift 2 ;;
    *) args+=("\$1"); shift ;;
  esac
done
prs="$fake/prs.json"
case "\${args[0]:-} \${args[1]:-}" in
  "pr view")
    ref=\${args[2]:-\$(git branch --show-current)}
    out=\$(jq -c --arg r "\$ref" 'map(select((.number|tostring)==\$r or .headRefName==\$r))[0] // empty' "\$prs")
    [ -n "\$out" ] || { echo "no pull requests found for branch \"\$ref\"" >&2; exit 1; } ;;
  "pr list")
    out=\$(jq -c --arg h "\${head:-}" --arg s "\${state:-open}" 'map(select((\$h=="" or .headRefName==\$h) and (\$s=="all" or (.state|ascii_downcase)==\$s)))' "\$prs") ;;
  *) out='{}' ;;
esac
if [ -n "\$jq_expr" ]; then jq -r "\$jq_expr" <<<"\$out"; else echo "\$out"; fi
EOF

cat > "$dir/bin/herdr" <<EOF
#!/usr/bin/env bash
echo "herdr \$*" >> "$dir/calls.log"
case "\${1:-} \${2:-}" in
  "tab get") jq -c --arg t "\${3:-}" '{result: {tab: {tab_id: \$t, pane_count: (.[\$t] // 0)}}}' "$fake/tabs.json" ;;
  "pane get") cat "$fake/pane.json" ;;
  "pane list") cat "$fake/panes.json" ;;
  *) echo '{}' ;;
esac
EOF
chmod +x "$dir/bin/gh" "$dir/bin/herdr"

printf 'HERDR_ENV=1\nHERDR_PANE_ID=%s\nHERDR_TAB_ID=%s\n' "$pane_id" "$tab_id" > "$dir/env"
